/**
  ******************************************************************************
  * @file    board.h
  * @brief   Board wiring - the single place where the board is pinned out.
  *
  *  Target: WeAct STM32G431CxUx Core Board V1.0 + 1.47" ST7789 SPI module.
  *
  *    LCD pin   MCU pin   function                      .ioc / main.h label
  *    -------   -------   ---------------------------   -------------------
  *    SCL       PA5       SPI1_SCK   (AF5)              SPI1
  *    SDA       PA7       SPI1_MOSI  (AF5)              SPI1
  *    CS        PA3       GPIO output                   LCD_CS
  *    DC        PA1       GPIO output                   LCD_DC
  *    RES       PB0       GPIO output                   LCD_RST
  *    BLK       PB1       GPIO output                   LCD_BLK
  *    VCC       3V3, GND  GND
  *
  *    KEY       PC13      GPIO input, pressed = high    KEY
  *    LED       PC6       GPIO output, lit when low     (unused)
  *
  *  * The pins, SPI1, DMA1_Channel2 for SPI1_TX and PC13 are all generated by
  *  CubeMX from stm32g431cbu6_Project.ioc:
  *
  *      Core/Src/gpio.c     MX_GPIO_Init()  LCD_CS/LCD_DC/LCD_RST/LCD_BLK/KEY
  *      Core/Src/dma.c      MX_DMA_Init()   DMA1 + DMAMUX1 clocks, DMA1_Ch2 interrupt
  *      Core/Src/spi.c      MX_SPI1_Init()  hspi1 + hdma_spi1_tx + PA5/PA7 (AF5)
  *      Core/Inc/main.h     KEY_/LCD_*_Pin / _GPIO_Port
  *
  *  So this file **defines no pin numbers at all** any more; it only maps the
  *  board-level names onto the generated macros, and the BSP contains no
  *  HAL_GPIO_Init() or SPI/DMA register configuration either. To change a pin:
  *  edit the .ioc -> regenerate the code -> the mapping here hardly has to move.
  *
  *  PC13 electrical wiring (board schematic): PC13 -- R4(330R) -- SW2 -- 3.3V.
  *  Pressing pulls the pin to a high level and releasing leaves it floating,
  *  which is why the .ioc configures GPIO_Input + GPIO_PULLDOWN (internal
  *  pull-down, guaranteeing that a definite low level is read when released).
  ******************************************************************************
  */
#ifndef BOARD_H
#define BOARD_H

#include "main.h"

/* --- transport ------------------------------------------------------------ */
/* SPI1 is generated by CubeMX in Core/Src/spi.c: hspi1 (SPI_HandleTypeDef)
   and hdma_spi1_tx (DMA_HandleTypeDef). The transport layer uses those two
   handles directly; board_lcd.c only has to #include "spi.h", and no extra
   macro wrapper is needed here. */

/* --- control lines -------------------------------------------------------- */
#define BOARD_LCD_CS_PORT LCD_CS_GPIO_Port
#define BOARD_LCD_CS_PIN LCD_CS_Pin

#define BOARD_LCD_DC_PORT LCD_DC_GPIO_Port
#define BOARD_LCD_DC_PIN LCD_DC_Pin

#define BOARD_LCD_RST_PORT LCD_RST_GPIO_Port
#define BOARD_LCD_RST_PIN LCD_RST_Pin

#define BOARD_LCD_BL_PORT LCD_BLK_GPIO_Port
#define BOARD_LCD_BL_PIN LCD_BLK_Pin

/* --- user key ------------------------------------------------------------- */
/* Pressing reads as a high level (see the schematic note at the top of the
   file). */
#define BOARD_KEY_PORT KEY_GPIO_Port
#define BOARD_KEY_PIN KEY_Pin
#define BOARD_KEY_PRESSED_LEVEL GPIO_PIN_SET

#endif /* BOARD_H */
