/**
  ******************************************************************************
  * @file    board_lcd.c
  * @brief   LCD transport for the WeAct STM32G431 core board.
  *
  *  Implements lcd_bus_t on top of the SPI1 + DMA1_Channel2 (DMAMUX request 11)
  *  instance that CubeMX generates from stm32g431cbu6_Project.ioc.
  *
  *  * There is **no** pin / clock / peripheral initialisation here at all:
  *  SPI1 (master, half-duplex single-wire transmit, mode 0, BR=/4 -> 42.5 MHz),
  *  AF5 on PA5/PA7, the four CS/DC/RST/BLK outputs, the DMAMUX request of
  *  DMA1_Channel2, and the DMA interrupt are all written in the .ioc and
  *  generated by CubeMX into Core/Src/{gpio,dma,spi}.c and Core/Inc/main.h.
  *  The BSP is responsible for exactly one thing, "pushing bytes and pixels to
  *  the panel", so regenerating code will not fight with the BSP.
  *
  *  Why the frame length (DataSize) is changed at runtime
  *  --------------------------------
  *  A command or parameter is only a few bytes, so polling them out with an
  *  8 bit frame is the easiest thing to do; pixels are a continuous stream of
  *  tens of thousands of bytes each time and must use a 16 bit frame + DMA --
  *  one DMA request moves one RGB565 pixel, which is the only way to keep the
  *  SPI TX FIFO fed; with an 8 bit frame the DMA would have to arbitrate the
  *  bus per byte and the pixel rate would roughly halve.
  *
  *  DS can only be modified while the SPI is disabled; HAL_SPI_Init() disables
  *  the peripheral, rewrites CR1/CR2 and enables it again for us, so switching
  *  the frame length means writing hspi1.Init.DataSize and then re-running
  *  Init once.
  ******************************************************************************
  */
#include "board.h"
#include "lcd_bus.h"
#include "spi.h"

/** Timeout for the polled transmit: a command is only a few bytes, so 100 ms
    is already very generous. */
#define LCD_SPI_TIMEOUT_MS 100u

/** The current CR2.DS field, so that every transfer does not have to
    reconfigure the peripheral. The power-up value comes from
    MX_SPI1_Init(). */
static uint16_t s_datasize = SPI_DATASIZE_8BIT;

/* -------------------------------------------------------------------------- */
/* small helpers                                                              */
/* -------------------------------------------------------------------------- */

static inline void pin__write(GPIO_TypeDef *port, uint16_t pin, int level)
{
    HAL_GPIO_WritePin(port, pin, (level != 0) ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

/** Wait until the previous transfer has really finished: the HAL puts the
    state back to READY in the DMA complete interrupt. */
static void lcd__wait_ready(void)
{
    while (hspi1.State != HAL_SPI_STATE_READY)
    {
    }
}

/** Switch between the 8/16 bit frame. DS can only be changed while the SPI is
    disabled, which is left to HAL_SPI_Init(). */
static void lcd__set_datasize(uint16_t ds)
{
    if (s_datasize == ds)
    {
        return;
    }

    hspi1.Init.DataSize = ds;
    if (HAL_SPI_Init(&hspi1) != HAL_OK)
    {
        return;
    }
    s_datasize = ds;
}

/* -------------------------------------------------------------------------- */
/* transport implementation                                                   */
/* -------------------------------------------------------------------------- */

static int bus__init(void *ctx)
{
    (void)ctx;

    /* All hardware initialisation happens in main() (MX_GPIO_Init ->
       MX_DMA_Init -> MX_SPI1_Init, all generated from the .ioc); here we only
       align the recorded frame length with the value MX_SPI1_Init() wrote
       into CR2. */
    s_datasize = SPI_DATASIZE_8BIT;
    return 0;
}

static void bus__reset(void *ctx, int level)
{
    (void)ctx;
    pin__write(BOARD_LCD_RST_PORT, BOARD_LCD_RST_PIN, level);
}

static void bus__dc(void *ctx, int level)
{
    (void)ctx;
    pin__write(BOARD_LCD_DC_PORT, BOARD_LCD_DC_PIN, level);
}

static void bus__backlight(void *ctx, uint8_t percent)
{
    (void)ctx;
    pin__write(BOARD_LCD_BL_PORT, BOARD_LCD_BL_PIN, (percent > 0u) ? 1 : 0);
}

static void bus__delay_ms(void *ctx, uint32_t ms)
{
    (void)ctx;
    HAL_Delay(ms);
}

static void bus__write(void *ctx, const uint8_t *data, uint32_t len)
{
    (void)ctx;

    if ((data == NULL) || (len == 0u))
    {
        return;
    }

    lcd__wait_ready();
    lcd__set_datasize(SPI_DATASIZE_8BIT);

    pin__write(BOARD_LCD_CS_PORT, BOARD_LCD_CS_PIN, 0);
    (void)HAL_SPI_Transmit(&hspi1, data, (uint16_t)len, LCD_SPI_TIMEOUT_MS);
    lcd__wait_ready();
    pin__write(BOARD_LCD_CS_PORT, BOARD_LCD_CS_PIN, 1);
}

static void bus__write_pixels(void *ctx, const uint16_t *pixels, uint32_t count)
{
    (void)ctx;

    if ((pixels == NULL) || (count == 0u))
    {
        return;
    }

    lcd__wait_ready();
    /* One 16 bit frame is one RGB565 pixel: the SPI shifts the high byte out
       first, which is exactly the order the ST7789 expects, so the buffer
       needs no byte swapping. The DMA is configured in CubeMX as Half Word /
       Half Word aligned (see Dma.SPI1_TX.0.* in the .ioc), therefore the Size
       here is directly the **number of pixels**. */
    lcd__set_datasize(SPI_DATASIZE_16BIT);

    pin__write(BOARD_LCD_CS_PORT, BOARD_LCD_CS_PIN, 0);
    /* Asynchronous: CS must stay low until the pixels have been moved, and the
       caller finishes up with wait_idle(). */
    (void)HAL_SPI_Transmit_DMA(&hspi1, (const uint8_t *)pixels, (uint16_t)count);
}

static void bus__wait_idle(void *ctx)
{
    (void)ctx;

    lcd__wait_ready();
    pin__write(BOARD_LCD_CS_PORT, BOARD_LCD_CS_PIN, 1);
}

/* -------------------------------------------------------------------------- */
/* published bus                                                              */
/* -------------------------------------------------------------------------- */

static const lcd_bus_t s_lcd_bus = {
    .name = "spi1+dma1ch2",
    .init = bus__init,
    .reset = bus__reset,
    .dc = bus__dc,
    .backlight = bus__backlight,
    .delay_ms = bus__delay_ms,
    .write = bus__write,
    .write_pixels = bus__write_pixels,
    .wait_idle = bus__wait_idle,
};

const lcd_bus_t *board_lcd_bus(void)
{
    return &s_lcd_bus;
}
