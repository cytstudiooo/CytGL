/**
  ******************************************************************************
  * @file    board.h
  * @brief   Board wiring - the single place where the board is pinned out.
  *
  *  Target: STM32H563RGT6 (LQFP64) board + 1.47" ST7789 SPI module on the FPC1
  *  connector (see the board schematic, sheet "LCD drive circuit and connector").
  *
  *    LCD pin   MCU pin   function                      .ioc / main.h label
  *    -------   -------   ---------------------------   -------------------
  *    SCL       PB3       SPI1_SCK   (AF5)              SPI1
  *    SDA       PB5       SPI1_MOSI  (AF5)              SPI1
  *    CS        PA15      GPIO output                   LCD_CS
  *    DC        PB4       GPIO output                   LCD_DC
  *    RES       PB6       GPIO output                   LCD_RST
  *    LEDA      PB7       TIM4_CH2 PWM (AF2), 5 kHz     LCD_PWR
  *    VCC       3V3, GND  GND (FPC1 pins 7 / 2, 9, 10)
  *
  *    KEY       PC13      GPIO input, pressed = low     KEY
  *
  *  * The pins, SPI1, GPDMA1 channel 0 for SPI1_TX and PC13 are all generated
  *  by CubeMX from STM32H563RGT6_CytStudio_Demo.ioc:
  *
  *      Core/Src/gpio.c     MX_GPIO_Init()   LCD_CS/LCD_DC/LCD_RST/KEY
  *      Core/Src/tim.c      MX_TIM4_Init()   htim4 + PB7 (AF2) as TIM4_CH2 PWM
  *      Core/Src/gpdma.c    MX_GPDMA1_Init() GPDMA1 clock + channel 0 interrupt
  *      Core/Src/spi.c      MX_SPI1_Init()   hspi1 + handle_GPDMA1_Channel0
  *      Core/Inc/main.h     KEY_Pin / LCD_*_Pin / _GPIO_Port
  *
  *  So this file **defines no pin numbers at all** any more; it only maps the
  *  board-level names onto the generated macros, and the BSP contains no
  *  HAL_GPIO_Init() or SPI/DMA register configuration either. To change a pin:
  *  edit the .ioc -> regenerate the code -> the mapping here hardly has to move.
  *
  *  LCD_PWR electrical wiring (board schematic): Q1 is a high-side switch
  *  between 3V3 and LEDA (FPC1 pin 1), annotated "PMOS" on the schematic, with
  *  its gate tied to GND through R4 (10K) and driven from the MCU through
  *  R3 (1K). A PMOS high-side switch conducts when its gate is pulled low
  *  (Vgs = -3V3), so LCD_PWR is an **active-low** enable: PB7 low powers LEDA,
  *  PB7 high turns it off. That is what the pre-PWM firmware relied on
  *  (BOARD_LCD_BL_ON_LEVEL used to be GPIO_PIN_RESET) and the panel lit up, so
  *  it is also what BOARD_LCD_BL_PWM_ACTIVE_HIGH = 0 encodes here.
  *
  *  The polarity is not a matter of opinion: with the PWM up and a 20 % request
  *  the compare register really held 20 % (CCR2 = 160, PB7 confirmed toggling by
  *  reading GPIOB_IDR with the core halted) and the panel did *not* visibly dim
  *  -- an inverted mapping puts 80 % on-time on the LED, which is exactly "looks
  *  the same as before". With the macro below set correctly, 0 % is dark and
  *  100 % is full brightness. A board wired active-high needs it set to 1, which
  *  inverts the duty cycle in software (no .ioc change needed).
  *
  *  Because PB7 is a timer output and not a GPIO any more, "backlight on" is a
  *  duty cycle rather than a level: TIM4 runs from the APB1 timer clock
  *  (248 MHz, APB1 = HCLK/1), prescaler 61 gives a 4 MHz counter, period 799
  *  gives 5 kHz with 800 duty steps (0.125 % per step). 5 kHz is a common
  *  backlight choice: far above the flicker the eye sees when a panel is driven
  *  at a few hundred Hz, and far below the point where the R3/R4 gate drive
  *  would round the edges off. Dimming is then just a compare value, so the
  *  panel can be faded instead of switched.
  *
  *  PC13 electrical wiring (board schematic): PC13 -- USER1 -- GND, with no
  *  external pull-up, which is why the .ioc configures GPIO_Input +
  *  GPIO_PULLUP (internal pull-up, guaranteeing that a definite high level is
  *  read when released).
  ******************************************************************************
  */
#ifndef BOARD_H
#define BOARD_H

#include "main.h"

/* --- transport ------------------------------------------------------------ */
/* SPI1 is generated by CubeMX in Core/Src/spi.c: hspi1 (SPI_HandleTypeDef).
   The DMA side (handle_GPDMA1_Channel0) is linked into it by HAL_SPI_MspInit(),
   so the transport never has to name it; board_lcd.c only has to
   #include "spi.h", and no extra macro wrapper is needed here. */

/* --- control lines -------------------------------------------------------- */
#define BOARD_LCD_CS_PORT LCD_CS_GPIO_Port
#define BOARD_LCD_CS_PIN LCD_CS_Pin

#define BOARD_LCD_DC_PORT LCD_DC_GPIO_Port
#define BOARD_LCD_DC_PIN LCD_DC_Pin

#define BOARD_LCD_RST_PORT LCD_RST_GPIO_Port
#define BOARD_LCD_RST_PIN LCD_RST_Pin

/* --- backlight / panel power ---------------------------------------------- */
/* PB7 is TIM4_CH2 in PWM mode 1, configured by CubeMX in Core/Src/tim.c
   (htim4). Everything the BSP needs to know about it lives here, so the duty
   cycle can be changed without touching the .ioc (see the note at the top of
   the file for the 5 kHz / 800-step timing and for the active-high measurement
   that BOARD_LCD_BL_PWM_ACTIVE_HIGH encodes). */
#define BOARD_LCD_BL_PWM_CHANNEL TIM_CHANNEL_2
/** ARR + 1: the CCR value that means 100 % duty. */
#define BOARD_LCD_BL_PWM_STEPS 800u
/** 1 = a high level lights the backlight; 0 = invert the duty cycle, which is
    what the active-low (PMOS high-side) switch on this board needs -- see the
    schematic note at the top of this file. */
#define BOARD_LCD_BL_PWM_ACTIVE_HIGH 0

/* --- user key ------------------------------------------------------------- */
/* USER1 shorts PC13 to GND, so pressing reads as a low level (see the
   schematic note at the top of the file). */
#define BOARD_KEY_PORT KEY_GPIO_Port
#define BOARD_KEY_PIN KEY_Pin
#define BOARD_KEY_PRESSED_LEVEL GPIO_PIN_RESET

#endif /* BOARD_H */
