/**
  ******************************************************************************
  * @file    board_lcd.c
  * @brief   LCD transport for the STM32H563RGT6 board.
  *
  *  Implements lcd_bus_t on top of the SPI1 + GPDMA1 channel 0 (request
  *  SPI1_TX) instance that CubeMX generates from
  *  STM32H563RGT6_CytStudio_Demo.ioc.
  *
  *  * There is **no** pin / clock / peripheral initialisation here at all:
  *  SPI1 (master, transmit-only single direction, mode 0, BR=/8 -> 31 MBits/s),
  *  AF5 on PB3/PB5, the CS/DC/RST outputs, the backlight's TIM4_CH2 PWM on PB7,
  *  the GPDMA1 channel 0 request and the DMA interrupt are all written in the
  *  .ioc and generated by CubeMX into Core/Src/{gpio,spi,tim}.c and
  *  Core/Inc/main.h. The BSP is responsible for exactly one thing, "pushing
  *  bytes and pixels to the panel", so regenerating code will not fight with
  *  the BSP.
  *
  *  The one thing CubeMX deliberately leaves to the application is *enabling*
  *  the backlight PWM: MX_TIM4_Init() configures TIM4_CH2 (PWM mode 1, 5 kHz,
  *  800 duty steps -- see the timing note in BSP/board.h) but never calls
  *  HAL_TIM_PWM_Start(), so bus__init()/bus__backlight() do that on first use.
  *  Brightness is then only a compare value, which is what makes dimming (and
  *  fading) possible where the old GPIO write could only switch the panel on
  *  and off.
  *
  *  Why the frame length (DataSize) is changed at runtime
  *  --------------------------------
  *  A command or parameter is only a few bytes, so polling them out with an
  *  8 bit frame is the easiest thing to do; pixels are a continuous stream of
  *  tens of thousands of bytes each time and must use a 16 bit frame + DMA --
  *  one DMA request moves one RGB565 pixel, which is the only way to keep the
  *  SPI TX FIFO fed; with an 8 bit frame the DMA would have to arbitrate the
  *  bus per byte and the pixel rate would roughly halve.
  *
  *  DS can only be modified while the SPI is disabled; HAL_SPI_Init() disables
  *  the peripheral, rewrites CFG1/CFG2 and enables it again for us, so switching
  *  the frame length means writing hspi1.Init.DataSize and then re-running
  *  Init once.
  ******************************************************************************
  */
#include "board.h"
#include "lcd_bus.h"
#include "spi.h"
#include "tim.h"

/** Timeout for the polled transmit: a command is only a few bytes, so 100 ms
    is already very generous. */
#define LCD_SPI_TIMEOUT_MS 100u

/** 100 % duty in CCR counts: the timer's ARR + 1 (BOARD_LCD_BL_PWM_STEPS). */
#define LCD_BL_PWM_STEPS ((uint32_t)BOARD_LCD_BL_PWM_STEPS)

/** The current CFG1.DS field, so that every transfer does not have to
    reconfigure the peripheral. The power-up value comes from
    MX_SPI1_Init(). */
static uint16_t s_datasize = SPI_DATASIZE_8BIT;

/** Set once TIM4_CH2 has been started: CubeMX configures the channel but leaves
    starting it to the application. */
static uint8_t s_backlight_running;

/* -------------------------------------------------------------------------- */
/* small helpers                                                              */
/* -------------------------------------------------------------------------- */

static inline void pin__write(GPIO_TypeDef *port, uint16_t pin, GPIO_PinState state)
{
    HAL_GPIO_WritePin(port, pin, state);
}

/** Wait until the previous transfer has really finished: the HAL puts the
    state back to READY in the DMA complete interrupt. */
static void lcd__wait_ready(void)
{
    while (hspi1.State != HAL_SPI_STATE_READY)
    {
    }
}

/** Switch between the 8/16 bit frame. DS can only be changed while the SPI is
    disabled, which is left to HAL_SPI_Init(). */
static void lcd__set_datasize(uint16_t ds)
{
    if (s_datasize == ds)
    {
        return;
    }

    hspi1.Init.DataSize = ds;
    if (HAL_SPI_Init(&hspi1) != HAL_OK)
    {
        return;
    }
    s_datasize = ds;
}

/* -------------------------------------------------------------------------- */
/* transport implementation                                                   */
/* -------------------------------------------------------------------------- */

/** Map a brightness percentage onto a CCR value.
 *
 *  PB7 = TIM4_CH2 is a timer output now, so "on" is a duty cycle instead of a
 *  static level -- but `percent` always means the LED's on-time, whichever way
 *  the switch is wired. BOARD_LCD_BL_PWM_ACTIVE_HIGH carries the board's
 *  polarity (this board is active-low, see the schematic note in BSP/board.h);
 *  the #else branch is the only place that has to care and it just inverts. */
static uint32_t bl__ccr(uint8_t percent)
{
    uint32_t duty;

    if (percent > 100u)
    {
        percent = 100u;
    }

    /* 800 steps, so the rounding error is at most half of 0.125 %. */
    duty = ((uint32_t)percent * LCD_BL_PWM_STEPS) / 100u;

#if BOARD_LCD_BL_PWM_ACTIVE_HIGH
    return duty;
#else
    return LCD_BL_PWM_STEPS - duty;
#endif
}

/** Start the backlight PWM channel on first use, leaving it dark (CCR = 0). */
static void bl__start(void)
{
    if (s_backlight_running == 0u)
    {
        (void)HAL_TIM_PWM_Start(&htim4, BOARD_LCD_BL_PWM_CHANNEL);
        __HAL_TIM_SET_COMPARE(&htim4, BOARD_LCD_BL_PWM_CHANNEL, bl__ccr(0u));
        s_backlight_running = 1u;
    }
}

static int bus__init(void *ctx)
{
    (void)ctx;

    /* All hardware initialisation happens in main() (MX_GPIO_Init ->
       MX_GPDMA1_Init -> MX_SPI1_Init -> MX_TIM4_Init, all generated from the
       .ioc); here we only align the recorded frame length with the value
       MX_SPI1_Init() wrote into CFG1 and get the backlight PWM running dark. */
    s_datasize = SPI_DATASIZE_8BIT;
    s_backlight_running = 0u;
    bl__start();
    return 0;
}

static void bus__reset(void *ctx, int level)
{
    (void)ctx;
    pin__write(BOARD_LCD_RST_PORT, BOARD_LCD_RST_PIN,
               (level != 0) ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

static void bus__dc(void *ctx, int level)
{
    (void)ctx;
    pin__write(BOARD_LCD_DC_PORT, BOARD_LCD_DC_PIN,
               (level != 0) ? GPIO_PIN_SET : GPIO_PIN_RESET);
}

static void bus__backlight(void *ctx, uint8_t percent)
{
    (void)ctx;

    /* PB7 belongs to TIM4_CH2 (AF2), so writing the GPIO would do nothing: the
       brightness is the compare value of the PWM channel that CubeMX set up. */
    bl__start();
    __HAL_TIM_SET_COMPARE(&htim4, BOARD_LCD_BL_PWM_CHANNEL, bl__ccr(percent));
}

static void bus__delay_ms(void *ctx, uint32_t ms)
{
    (void)ctx;
    HAL_Delay(ms);
}

static void bus__write(void *ctx, const uint8_t *data, uint32_t len)
{
    (void)ctx;

    if ((data == NULL) || (len == 0u))
    {
        return;
    }

    lcd__wait_ready();
    lcd__set_datasize(SPI_DATASIZE_8BIT);

    pin__write(BOARD_LCD_CS_PORT, BOARD_LCD_CS_PIN, GPIO_PIN_RESET);
    (void)HAL_SPI_Transmit(&hspi1, data, (uint16_t)len, LCD_SPI_TIMEOUT_MS);
    lcd__wait_ready();
    pin__write(BOARD_LCD_CS_PORT, BOARD_LCD_CS_PIN, GPIO_PIN_SET);
}

static void bus__write_pixels(void *ctx, const uint16_t *pixels, uint32_t count)
{
    (void)ctx;

    if ((pixels == NULL) || (count == 0u))
    {
        return;
    }

    lcd__wait_ready();
    /* One 16 bit frame is one RGB565 pixel: the SPI shifts the high byte out
       first, which is exactly the order the ST7789 expects, so the buffer
       needs no byte swapping. The DMA is configured in CubeMX as Half Word /
       Half Word aligned (see GPDMA1.SRCDATAWIDTH_GPDMACH0 in the .ioc),
       therefore the Size here is directly the **number of pixels**. */
    lcd__set_datasize(SPI_DATASIZE_16BIT);

    pin__write(BOARD_LCD_CS_PORT, BOARD_LCD_CS_PIN, GPIO_PIN_RESET);
    /* Asynchronous: CS must stay low until the pixels have been moved, and the
       caller finishes up with wait_idle(). */
    (void)HAL_SPI_Transmit_DMA(&hspi1, (const uint8_t *)pixels, (uint16_t)count);
}

static void bus__wait_idle(void *ctx)
{
    (void)ctx;

    lcd__wait_ready();
    pin__write(BOARD_LCD_CS_PORT, BOARD_LCD_CS_PIN, GPIO_PIN_SET);
}

/* -------------------------------------------------------------------------- */
/* published bus                                                              */
/* -------------------------------------------------------------------------- */

static const lcd_bus_t s_lcd_bus = {
    .name = "spi1+gpdma1ch0",
    .init = bus__init,
    .reset = bus__reset,
    .dc = bus__dc,
    .backlight = bus__backlight,
    .delay_ms = bus__delay_ms,
    .write = bus__write,
    .write_pixels = bus__write_pixels,
    .wait_idle = bus__wait_idle,
};

const lcd_bus_t *board_lcd_bus(void)
{
    return &s_lcd_bus;
}
