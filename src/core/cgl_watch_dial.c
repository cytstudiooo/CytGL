/**
  ******************************************************************************
  * @file    cgl_watch_dial.c
  * @brief   The watch module's two **default** dial surfaces, as data in flash.
  *
  *  Why these exist
  *  ---------------
  *  A dial's face and the ring it is set into are "one colour per pixel, out of a
  *  table" (see cgl_arc.h): the table carries the gradient, the circular brushing
  *  and the ring's cross-section, and only the sunburst, the highlight and the tilt
  *  are evaluated per pixel on top of it. A caller who just wants a watch should not
  *  have to own two tables to get one, so `cgl_watch_config_default()` points its
  *  two `cgl_arc_surface_t`s at the arrays below -- 578 bytes of flash on a part
  *  whose flash is mostly empty, against the same 578 bytes of RAM the tables would
  *  otherwise cost a 32 KB part that has none to spare.
  *
  *  Why they are inside `CGL_CFG_WATCH_DIAL_LUT`
  *  -------------------------------------------
  *  A UI that draws no watch should not carry a watch dial. With the switch off this
  *  translation unit is empty **and** `cgl_watch_config_default()` leaves both `lut`
  *  pointers NULL, so a surface built by it shades procedurally instead: the same
  *  colours from the same parameters, a little more CPU per pixel, and no flash at
  *  all.
  *
  *  Why the generator is not here
  *  -----------------------------
  *  It is `cgl_arc_surface_bake()`, which is public, and that is the whole point: the
  *  code that would produce the table **is** the code that ships, rather than a second
  *  copy of the arithmetic that can drift from it. `tools/mkwatchlut.c` is a thin
  *  wrapper that prints what the baker produces, and `tests/watch_host_test.c`
  *  re-runs that same baker over every entry of both arrays below -- so "the table
  *  rotted" is a test failure that prints the regenerated array, and not a palette
  *  that quietly stopped matching its constants.
  *
  *  Regenerating after a deliberate palette or geometry change:
  *
  *      build/mkwatchlut > build/watch_lut.txt     (see tools/mkwatchlut.c for the
  *                                                 exact command line)
  *
  *  and paste its output over the two arrays below.
  ******************************************************************************
  */
